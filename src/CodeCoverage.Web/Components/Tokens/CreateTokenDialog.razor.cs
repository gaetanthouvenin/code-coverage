using Mediator;

using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Forms;
using Microsoft.Extensions.Localization;

using CodeCoverage.Web.Messaging;
using CodeCoverage.Web.Resources;
using CodeCoverage.Web.ViewModels.Tokens;

namespace CodeCoverage.Web.Components.Tokens;

/// <summary>
///   Creates a token with a name. The value is generated by the server and given back once, to the dialog that shows
///   it; this one never keeps it.
/// </summary>
public partial class CreateTokenDialog
{
  #region Fields

  private TokenForm _form = new();

  private EditContext _editContext = null!;

  private bool _busy;

  #endregion

  #region Parameters

  /// <summary>Gets or sets a value indicating whether the dialog is shown.</summary>
  [Parameter]
  public bool Open { get; set; }

  /// <summary>Gets or sets how the token is created: the page knows what it belongs to.</summary>
  [Parameter, EditorRequired]
  public Func<ISender, string, CancellationToken, Task<IssuedTokenViewModel?>> Create { get; set; } = null!;

  /// <summary>Gets or sets what happens once the token is created, with its value shown this one time.</summary>
  [Parameter]
  public EventCallback<IssuedTokenViewModel> OnCreated { get; set; }

  /// <summary>Gets or sets what happens when the dialog closes without creating anything.</summary>
  [Parameter]
  public EventCallback OnClosed { get; set; }

  #endregion

  #region Injected services

  [Inject]
  private UiRequestRunner Runner { get; set; } = null!;

  [Inject]
  private IStringLocalizer<Common> L { get; set; } = null!;

  #endregion

  #region Lifecycle

  /// <inheritdoc />
  protected override void OnInitialized() => _editContext = new EditContext(_form);

  #endregion

  #region Methods

  private string? Error(string field) => _editContext.GetValidationMessages(_editContext.Field(field)).FirstOrDefault();

  private async Task CreateAsync()
  {
    if (string.IsNullOrWhiteSpace(_form.Label))
    {
      return;
    }

    _busy = true;

    try
    {
      var label = _form.Label;
      var result = await Runner.RunAsync((sender, ct) => Create(sender, label, ct), _editContext).ConfigureAwait(true);

      if (result is { Succeeded: true, Value: { } issued })
      {
        Reset();
        await OnCreated.InvokeAsync(issued).ConfigureAwait(true);
      }
    }
    finally
    {
      _busy = false;
    }
  }

  private Task CloseAsync()
  {
    Reset();

    return OnClosed.InvokeAsync();
  }

  private void Reset()
  {
    _form = new TokenForm();
    _editContext = new EditContext(_form);
  }

  #endregion
}
