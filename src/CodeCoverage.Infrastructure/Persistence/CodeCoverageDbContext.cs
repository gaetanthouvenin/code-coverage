namespace CodeCoverage.Infrastructure.Persistence;

/// <summary>The CodeCoverage database, on PostgreSQL or SQL Server.</summary>
/// <param name="options">The context options (engine and migrations assembly).</param>
/// <param name="currentOrganization">The organization of the scope, read by the query filter and by the save.</param>
/// <remarks>
///   <para>
///     One model serves both engines: the entity configurations
///     (<c>Persistence/Configurations/{Entity}Configuration</c>) hold no engine-specific SQL, and each
///     engine has its own migrations assembly.
///   </para>
///   <para>
///     Conventions: <see langword="long" /> keys are <c>bigint</c> identity columns
///     (<c>GENERATED BY DEFAULT AS IDENTITY</c> / <c>IDENTITY(1,1)</c>), the default value generation
///     strategy of both providers, and enumerations are stored as text
///     (<see cref="EnumAsStringConvention" />). The provider defaults are not restated here: an
///     annotation of one provider would leak into the model snapshot of the other. The one exception is the
///     collation of the case-sensitive columns, given on SQL Server only, whose default collation ignores the case.
///   </para>
///   <para>
///     The context also holds the Data Protection key ring (<see cref="IDataProtectionKeyContext" />),
///     shared by the Api and the Web.
///   </para>
///   <para>
///     Every entity declared by <see cref="OrganizationOwnedExtensions.IsOrganizationOwned{TEntity}" /> gets the
///     same named query filter, which covers the queries, <c>ExecuteUpdate</c> and <c>ExecuteDelete</c>. It reads
///     the organization of this context each time a query runs, although the model is built once and shared, and
///     has no clause for the system principal: without an organization, the query throws (ADR-013).
///   </para>
///   <para>
///     Saving stamps the added rows of those entities with the organization of this context and refuses the
///     modified or deleted rows of another one. The shadow column does not travel with an instance: a row must be
///     read through this context before it can be changed, and an attached instance is refused.
///   </para>
///   <para>
///     The shadow column is also a concurrency token, so a statement that passed the guard still filters on the
///     organization: a statement that affects no row is refused with a <see cref="ConflictException" />, the same
///     way for a row removed meanwhile, an unknown key and a key of another organization (ADR-013).
///   </para>
/// </remarks>
public sealed class CodeCoverageDbContext(
  DbContextOptions<CodeCoverageDbContext> options,
  ICurrentOrganization currentOrganization) : DbContext(options), IDataProtectionKeyContext
{
  #region Fields

  /// <summary>The SQL Server collation of the case-sensitive columns: a comparison by code point.</summary>
  private const string SqlServerOrdinalCollation = "Latin1_General_100_BIN2";

  /// <summary>The message of the refusal of a row that does not belong to the organization of the scope.</summary>
  private const string ForeignRowMessage = "The row belongs to another organization.";

  /// <summary>The message of the refusal of a save that affected no row; it is sent to the caller.</summary>
  private const string NoRowAffectedMessage = "The data was changed or removed in the meantime; reload it and try again.";

  #endregion

  #region Properties

  /// <summary>Gets the audit trail (<c>AuditEntries</c>).</summary>
  public DbSet<AuditEntry> AuditEntries => Set<AuditEntry>();

  /// <summary>Gets the branches of the tracked repositories (<c>Branches</c>).</summary>
  public DbSet<Branch> Branches => Set<Branch>();

  /// <summary>Gets the commits of the tracked repositories (<c>Commits</c>).</summary>
  public DbSet<Commit> Commits => Set<Commit>();

  /// <summary>Gets what was found as the configuration of the commits (<c>CommitConfigs</c>).</summary>
  public DbSet<CommitConfig> CommitConfigs => Set<CommitConfig>();

  /// <summary>Gets the totals of the commits by flag (<c>CommitFlagTotals</c>).</summary>
  public DbSet<CommitFlagTotals> CommitFlagTotals => Set<CommitFlagTotals>();

  /// <summary>Gets the merged reports of the commits (<c>CommitReports</c>).</summary>
  internal DbSet<CommitReportRecord> CommitReports => Set<CommitReportRecord>();

  /// <summary>Gets the comparisons computed for the commits (<c>Comparisons</c>).</summary>
  internal DbSet<ComparisonRecord> Comparisons => Set<ComparisonRecord>();

  /// <summary>Gets the cached diffs (<c>DiffCache</c>).</summary>
  internal DbSet<DiffCacheRecord> DiffCache => Set<DiffCacheRecord>();

  /// <summary>Gets the sessions of the commits (<c>CommitSessions</c>).</summary>
  public DbSet<Session> CommitSessions => Set<Session>();

  /// <inheritdoc />
  public DbSet<DataProtectionKey> DataProtectionKeys => Set<DataProtectionKey>();

  /// <summary>Gets the cache of the commit metadata read from the forges (<c>GitCommits</c>).</summary>
  public DbSet<GitCommit> GitCommits => Set<GitCommit>();

  /// <summary>Gets the installations of the GitHub App (<c>Installations</c>).</summary>
  public DbSet<Installation> Installations => Set<Installation>();

  /// <summary>Gets the background jobs (<c>Jobs</c>).</summary>
  internal DbSet<JobRecord> Jobs => Set<JobRecord>();

  /// <summary>Gets the organizations hosted by the instance (<c>Organizations</c>).</summary>
  public DbSet<Organization> Organizations => Set<Organization>();

  /// <summary>Gets the values saved by the organizations (<c>OrganizationSettings</c>).</summary>
  internal DbSet<StoredOrganizationSetting> OrganizationSettings => Set<StoredOrganizationSetting>();

  /// <summary>Gets the pull requests of the tracked repositories (<c>PullRequests</c>).</summary>
  public DbSet<PullRequest> PullRequests => Set<PullRequest>();

  /// <summary>Gets the tracked repositories (<c>Repositories</c>).</summary>
  public DbSet<TrackedRepository> Repositories => Set<TrackedRepository>();

  /// <summary>Gets the cache of the file trees read from the forges (<c>RepositoryTrees</c>).</summary>
  internal DbSet<RepositoryTreeRecord> RepositoryTrees => Set<RepositoryTreeRecord>();

  /// <summary>Gets the values saved in the settings store (<c>Settings</c>).</summary>
  internal DbSet<StoredSetting> Settings => Set<StoredSetting>();

  /// <summary>Gets the single row of the settings revision (<c>SettingsRevision</c>).</summary>
  internal DbSet<SettingsRevisionRow> SettingsRevisions => Set<SettingsRevisionRow>();

  /// <summary>Gets the coverage of the processed uploads (<c>UploadCoverages</c>).</summary>
  internal DbSet<UploadCoverageRecord> UploadCoverages => Set<UploadCoverageRecord>();

  /// <summary>Gets the chunks of the stored parts of the uploads (<c>UploadRawChunks</c>).</summary>
  internal DbSet<UploadRawChunkRecord> UploadRawChunks => Set<UploadRawChunkRecord>();

  /// <summary>Gets the stored parts of the uploads (<c>UploadRawFiles</c>).</summary>
  internal DbSet<UploadRawFileRecord> UploadRawFiles => Set<UploadRawFileRecord>();

  /// <summary>Gets the upload tokens (<c>UploadTokens</c>).</summary>
  public DbSet<UploadToken> UploadTokens => Set<UploadToken>();

  /// <summary>Gets the uploads of the commits (<c>Uploads</c>).</summary>
  public DbSet<Upload> Uploads => Set<Upload>();

  /// <summary>Gets the users who signed in (<c>Users</c>).</summary>
  public DbSet<AppUser> Users => Set<AppUser>();

  /// <summary>Gets the accesses of the users to the repositories (<c>UserRepositoryAccess</c>).</summary>
  public DbSet<RepositoryAccess> UserRepositoryAccess => Set<RepositoryAccess>();

  /// <summary>Gets the webhook deliveries (<c>WebhookDeliveries</c>).</summary>
  internal DbSet<WebhookDeliveryRecord> WebhookDeliveries => Set<WebhookDeliveryRecord>();

  /// <summary>Gets the identifier of the organization of the scope, read by the query filter and by the save.</summary>
  /// <exception cref="InvalidOperationException">The scope has not entered an organization.</exception>
  private long CurrentOrganizationId => currentOrganization.Id;

  #endregion

  #region Methods

  /// <inheritdoc />
  /// <exception cref="InvalidOperationException">
  ///   A written row of an organization table belongs to another organization, or the scope has not entered one.
  /// </exception>
  /// <exception cref="ConflictException">A statement on an organization table affected no row.</exception>
  public override int SaveChanges(bool acceptAllChangesOnSuccess)
  {
    ApplyOrganizationRules();

    try
    {
      return base.SaveChanges(acceptAllChangesOnSuccess);
    }
    catch (DbUpdateConcurrencyException exception) when (IsOrganizationRow(exception))
    {
      throw NoRowAffected(exception);
    }
  }

  /// <inheritdoc />
  /// <exception cref="InvalidOperationException">
  ///   A written row of an organization table belongs to another organization, or the scope has not entered one.
  /// </exception>
  /// <exception cref="ConflictException">A statement on an organization table affected no row.</exception>
  public override async Task<int> SaveChangesAsync(
    bool acceptAllChangesOnSuccess,
    CancellationToken cancellationToken = default)
  {
    ApplyOrganizationRules();

    try
    {
      return await base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken).ConfigureAwait(false);
    }
    catch (DbUpdateConcurrencyException exception) when (IsOrganizationRow(exception))
    {
      throw NoRowAffected(exception);
    }
  }

  /// <inheritdoc />
  protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
  {
    ArgumentNullException.ThrowIfNull(configurationBuilder);

    configurationBuilder.Conventions.Add(static _ => new EnumAsStringConvention());
  }

  /// <inheritdoc />
  protected override void OnModelCreating(ModelBuilder modelBuilder)
  {
    ArgumentNullException.ThrowIfNull(modelBuilder);

    modelBuilder.ApplyConfigurationsFromAssembly(typeof(CodeCoverageDbContext).Assembly);

    // A flag is case-sensitive, as on Codecov: SQL Server compares it by code point. The default collation of
    // PostgreSQL is deterministic, so its equality is already exact (its ORDER BY follows the locale); the default
    // collation of SQL Server would merge Backend and backend in the key.
    if (Database.IsSqlServer())
    {
      modelBuilder.Entity<CommitFlagTotals>().Property(static t => t.Flag).UseCollation(SqlServerOrdinalCollation);
    }

    foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(static e => e.IsMarkedOrganizationOwned()))
    {
      modelBuilder.Entity(entityType.ClrType)
                  .HasQueryFilter(OrganizationOwnedExtensions.FilterName, OrganizationFilter(entityType.ClrType));
    }
  }

  /// <summary>Builds the filter that keeps the rows of the organization of the scope.</summary>
  /// <param name="entity">The entity to filter.</param>
  /// <returns>
  ///   The predicate <c>e =&gt; EF.Property&lt;long&gt;(e, "OrganizationId") == this.CurrentOrganizationId</c>: EF
  ///   Core replaces <c>this</c> with the context that runs the query.
  /// </returns>
  private LambdaExpression OrganizationFilter(Type entity)
  {
    var row = Expression.Parameter(entity, "e");
    var owner = Expression.Call(
      typeof(EF),
      nameof(EF.Property),
      [typeof(long)],
      row,
      Expression.Constant(OrganizationOwnedExtensions.ColumnName)
    );
    var current = Expression.Property(Expression.Constant(this), nameof(CurrentOrganizationId));

    return Expression.Lambda(Expression.Equal(owner, current), row);
  }

  /// <summary>Tells whether a save failed on a row of an organization table.</summary>
  /// <param name="exception">The failure of the save.</param>
  /// <returns>
  ///   <see langword="true" /> for a row of an organization table. A global table keeps its own failure:
  ///   <c>Organizations</c> retries on it.
  /// </returns>
  private static bool IsOrganizationRow(DbUpdateConcurrencyException exception) =>
    exception.Entries.Any(static e => e.Metadata.IsMarkedOrganizationOwned());

  /// <summary>Builds the refusal of a statement that affected no row of an organization table.</summary>
  /// <param name="exception">The failure of the save.</param>
  /// <returns>The refusal.</returns>
  /// <remarks>
  ///   The database reports the same thing for a row removed meanwhile, an unknown key and a key of another
  ///   organization, so the caller gets one refusal for the three, and nothing tells them apart.
  /// </remarks>
  private static ConflictException NoRowAffected(DbUpdateConcurrencyException exception) =>
    new(GeneralErrors.ConcurrentChange, NoRowAffectedMessage, exception);

  /// <summary>Stamps the added rows of the organization tables and refuses the rows of another organization.</summary>
  /// <exception cref="InvalidOperationException">
  ///   A written row belongs to another organization, or the scope has not entered one.
  /// </exception>
  /// <remarks>
  ///   Runs before the save, so the statements and the unique indexes that hold the shadow column see the stamped
  ///   value. The organization is read only when such a row is written: saving the global and operational tables
  ///   needs none. A value of zero on a row that is not added means it was attached without being read here.
  /// </remarks>
  private void ApplyOrganizationRules()
  {
    var written = ChangeTracker.Entries<object>()
                               .Where(static e => e.State is EntityState.Added or EntityState.Modified or EntityState.Deleted)
                               .Where(static e => e.Metadata.IsMarkedOrganizationOwned());

    foreach (var entry in written)
    {
      var owner = entry.Property<long>(OrganizationOwnedExtensions.ColumnName);
      var current = CurrentOrganizationId;

      if (entry.State is EntityState.Added)
      {
        InvalidOperationException.ThrowIf(owner.CurrentValue != 0 && owner.CurrentValue != current, ForeignRowMessage);
        owner.CurrentValue = current;
      }
      else
      {
        InvalidOperationException.ThrowIf(owner.OriginalValue != current || owner.CurrentValue != current, ForeignRowMessage);
      }
    }
  }

  #endregion
}
